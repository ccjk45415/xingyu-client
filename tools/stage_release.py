"""Stage validated three-platform release downloads. Does not deploy or publish."""
import hashlib
import json
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / 'cloudflare-chat/public'
ORIGIN = 'https://xingyu-chat-ccjk45415.pages.dev'
notes = (ROOT / 'docs/RELEASE-0.12.0.md').read_text('utf-8').strip()
artifacts = [
    ('android', 'Cangku-Xingyu-0.12.0-arm64.apk', '0.12.0', 34, 'application/vnd.android.package-archive'),
    ('windows', 'Xingyu-Windows-0.6.0-x64.zip', '0.6.0', 25, 'application/zip'),
    ('macos', 'Xingyu-macOS-0.2.0-arm64.pkg', '0.2.0', 3, 'application/octet-stream'),
    (None, 'Xingyu-macOS-0.2.0-arm64.dmg', '0.2.0', 3, 'application/x-apple-diskimage'),
]
previous = ROOT / 'cloudflare-entry/release-index.mjs'
index = json.loads(previous.read_text('utf-8').split('export default ', 1)[1].strip().rstrip(';')) if previous.exists() else {}
records = []
for platform, name, version, code, content_type in artifacts:
    file = ROOT / 'output' / name
    assert file.is_file(), 'Build the installer first: ' + name
    size = file.stat().st_size
    digest = hashlib.sha256(file.read_bytes()).hexdigest()
    if platform == 'android': assert size <= 24 * 1024 * 1024, 'Original updater cannot accept this APK'
    if size > 24 * 1024 * 1024:
        chunks = []
        with file.open('rb') as source:
            while data := source.read(16 * 1024 * 1024):
                path = f'/release-chunks/{digest}/{len(chunks)}.part'
                destination = PUBLIC / path.lstrip('/')
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_bytes(data)
                chunks.append(path)
        index[name] = {'size': size, 'sha256': digest, 'type': content_type, 'chunks': chunks}
        reconstructed = hashlib.sha256()
        for path in chunks: reconstructed.update((PUBLIC / path.lstrip('/')).read_bytes())
        assert reconstructed.hexdigest() == digest
    else:
        (PUBLIC / 'releases').mkdir(exist_ok=True)
        shutil.copy2(file, PUBLIC / 'releases' / name)
    if platform:
        manifest = {'available': True, 'versionName': version, 'versionCode': code,
                    'notes': notes, 'url': ORIGIN + '/releases/' + name,
                    'size': size, 'sha256': digest}
        if platform == 'android': manifest.update(package='moe.cangku.reader', minSdk=26)
        else:
            manifest['platform'] = 'windows-x64' if platform == 'windows' else 'macos-arm64'
            manifest['product'] = 'moe.cangku.xingyu.desktop' if platform == 'windows' else 'moe.cangku.xingyu.macos'
        (PUBLIC / f'updates/{platform}.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    records.append({'file': name, 'bytes': size, 'sha256': digest, 'version': version, 'code': code})
(ROOT / 'cloudflare-entry/release-index.mjs').write_text(
    '// Public metadata; generated by tools/stage_release.py.\nexport default ' + json.dumps(index, indent=2) + ';\n', encoding='utf-8')
(ROOT / 'output/Release-0.12.0-SHA256SUMS.txt').write_text(
    ''.join(p['sha256'] + '  ' + p['file'] + '\n' for p in records), encoding='ascii')
(ROOT / 'evidence/release-0.12.0-staged.json').write_text(json.dumps({
    'status': 'staged_only', 'published': False, 'packages': records,
    'chunk_reconstruction_verified': True, 'notes': notes}, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
print(json.dumps({'staged': records, 'streamed_artifacts': len(index)}, ensure_ascii=False))
